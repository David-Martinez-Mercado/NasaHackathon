import { Field, Float, ID, InputType, Int, ObjectType } from '@nestjs/graphql';
import { Type } from 'class-transformer';
import {
  ArrayMaxSize,
  IsArray,
  IsInt,
  IsLatitude,
  IsLongitude,
  IsOptional,
  IsString,
  Matches,
  MaxLength,
  Min,
  MinLength,
  ValidateNested,
} from 'class-validator';
import { HistorialInput, RegistroHistorial } from '../historial/historial.model';
import { Preferencias, PreferenciasInput } from '../preferencias/preferencias.model';
import { GeometriaGeoJSON } from './geojson';
import { GeoJSONScalar } from './geojson.scalar';

@ObjectType()
export class Parcela {
  @Field(() => ID)
  id: string;

  @Field(() => String, { nullable: true })
  nombre?: string | null;

  @Field(() => String, { nullable: true })
  descripcion?: string | null;

  @Field(() => String, { nullable: true, description: 'Code of the crop planted today' })
  cultivoActual?: string | null;

  @Field(() => Float, { description: 'Latitude of the centroid' })
  latitud: number;

  @Field(() => Float, { description: 'Longitude of the centroid' })
  longitud: number;

  @Field(() => Float, { nullable: true, description: 'Hectares (only if the field is a polygon)' })
  areaHa?: number | null;

  @Field(() => GeoJSONScalar, { description: 'Shape of the field (Point or Polygon)' })
  geometria: GeometriaGeoJSON;

  @Field(() => Int, { description: 'Version for optimistic locking: send it when updating or deleting' })
  version: number;

  @Field(() => Date)
  creadaEn: Date;

  @Field(() => Date)
  actualizadaEn: Date;

  @Field(() => Preferencias, { nullable: true })
  preferencias?: Preferencias | null;

  @Field(() => [RegistroHistorial])
  historial?: RegistroHistorial[];
}

@InputType()
export class PuntoInput {
  @Field(() => Float)
  @IsLatitude({ message: 'The latitude must be between -90 and 90.' })
  latitud: number;

  @Field(() => Float)
  @IsLongitude({ message: 'The longitude must be between -180 and 180.' })
  longitud: number;
}

@InputType()
export class CrearParcelaInput {
  @Field(() => String, {
    nullable: true,
    description:
      'Key generated by the client (e.g. a UUID). If the creation is repeated with the same key, it is not duplicated: ' +
      'the already created field is returned.',
  })
  @IsOptional()
  @IsString()
  @MinLength(8, { message: 'The idempotency key needs at least 8 characters.' })
  @MaxLength(80, { message: 'The idempotency key can have up to 80 characters.' })
  @Matches(/^[A-Za-z0-9_.:-]+$/, { message: 'The idempotency key only uses letters, numbers and . _ : -' })
  claveIdempotencia?: string;

  @Field(() => String, { nullable: true })
  @IsOptional()
  @IsString()
  @MaxLength(120, { message: 'The name can have up to 120 characters.' })
  nombre?: string;

  @Field(() => String, { nullable: true })
  @IsOptional()
  @IsString()
  @MaxLength(500, { message: 'The description can have up to 500 characters.' })
  descripcion?: string;

  @Field(() => String, { nullable: true, description: 'Crop code (see the cultivos query)' })
  @IsOptional()
  @Matches(/^[a-z0-9_-]{1,40}$/, { message: 'Invalid crop code.' })
  cultivoActual?: string;

  @Field(() => PuntoInput, { nullable: true, description: 'Use punto or poligono, not both.' })
  @IsOptional()
  @ValidateNested()
  @Type(() => PuntoInput)
  punto?: PuntoInput;

  @Field(() => GeoJSONScalar, { nullable: true, description: 'GeoJSON polygon (longitude, latitude).' })
  @IsOptional()
  poligono?: GeometriaGeoJSON;

  @Field(() => PreferenciasInput, { nullable: true, description: 'Saved together with the field, in the same transaction.' })
  @IsOptional()
  @ValidateNested()
  @Type(() => PreferenciasInput)
  preferencias?: PreferenciasInput;

  @Field(() => [HistorialInput], { nullable: true, description: 'Years already planted; if one fails, nothing is created.' })
  @IsOptional()
  @IsArray()
  @ArrayMaxSize(60, { message: 'Maximum 60 years of history.' })
  @ValidateNested({ each: true })
  @Type(() => HistorialInput)
  historial?: HistorialInput[];
}

@InputType()
export class ActualizarParcelaInput {
  @Field(() => Int, { description: 'The field version the client read. If it changed, the update is rejected.' })
  @IsInt({ message: 'The version must be a whole number.' })
  @Min(1)
  version: number;

  @Field(() => String, { nullable: true, description: 'Omitted = unchanged; null = delete' })
  @IsOptional()
  @IsString()
  @MaxLength(120, { message: 'The name can have up to 120 characters.' })
  nombre?: string | null;

  @Field(() => String, { nullable: true, description: 'Omitted = unchanged; null = delete' })
  @IsOptional()
  @IsString()
  @MaxLength(500, { message: 'The description can have up to 500 characters.' })
  descripcion?: string | null;

  @Field(() => String, { nullable: true, description: 'Omitted = unchanged; null = delete' })
  @IsOptional()
  @Matches(/^[a-z0-9_-]{1,40}$/, { message: 'Invalid crop code.' })
  cultivoActual?: string | null;

  @Field(() => PuntoInput, { nullable: true, description: 'New location as a point (not combined with poligono).' })
  @IsOptional()
  @ValidateNested()
  @Type(() => PuntoInput)
  punto?: PuntoInput;

  @Field(() => GeoJSONScalar, { nullable: true, description: 'New shape as a polygon (not combined with punto).' })
  @IsOptional()
  poligono?: GeometriaGeoJSON;

  @Field(() => PreferenciasInput, {
    nullable: true,
    description: 'Replaces the field preferences, in the same transaction as the other changes.',
  })
  @IsOptional()
  @ValidateNested()
  @Type(() => PreferenciasInput)
  preferencias?: PreferenciasInput;
}
